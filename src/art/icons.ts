export function buildIcons(): Img[] {
  const i: Img[] = [];
  i[IC.Fists] = ol('Fists', FISTS);
  i[IC.Club] = ol('Club', CLUB);
  i[IC.Sword] = ol('Sword', SWORD);
  i[IC.Spear] = ol('Spear', SPEAR);
  i[IC.Bow] = ol('Bow', BOW);
  i[IC.Knives] = ol('Knives', KNIVES);
  i[IC.Firebolt] = ol('FireboltIcon', FIREBOLT);
  i[IC.Frost] = ol('FrostIcon', FROST);
  i[IC.Bombs] = ol('Bombs', BOMBS);
  i[IC.Cleaver] = shift(ol('Cleaver', CLEAVER), 1, 0);
  i[IC.Shield] = ol('ShieldIcon', SHIELD);
  i[IC.DashBoots] = ol('DashBoots', DASH_BOOTS);
  i[IC.Armour] = ol('Armour', ARMOUR);
  i[IC.Lantern] = ol('Lantern', LANTERN);
  i[IC.Magnet] = ol('Magnet', MAGNET);
  i[IC.Scroll] = ol('Scroll', SCROLL);
  i[IC.VigorRing] = ol('VigorRing', VIGOR_RING);
  i[IC.HeartUI] = ol('HeartUI', HEART_UI);
  i[IC.LifeUI] = ol('LifeUI', LIFE_UI);
  i[IC.GoldUI] = ol('GoldUI', GOLD_UI);
  i[IC.Renown] = ol('Renown', RENOWN);
  const key = spr('KeyUI', KEY_UI);
  i[IC.KeyRedUI] = outline(key);
  i[IC.KeyBlueUI] = outline(recolour(key, { R: 'U', r: 'u', o: 'c' }));
  i[IC.CharmHp] = ol('CharmHp', CHARM_HP);
  i[IC.CharmDmg] = ol('CharmDmg', CHARM_DMG);
  i[IC.Heal] = ol('Heal', HEAL);
  i[IC.Lock] = ol('Lock', LOCK);
  return i;
}
