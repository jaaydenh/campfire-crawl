export function buildFx(): Img[] {
  const f: Img[] = [];
  f[F.Slash0] = spr('Slash0', SLASH0);
  f[F.Slash1] = spr('Slash1', SLASH1);
  f[F.Punch] = ol('Punch', PUNCH, 'o');
  f[F.Thrust] = spr('Thrust', THRUST);
  f[F.Arrow] = ol('Arrow', ARROW);
  f[F.EnemyArrow] = ol('EnemyArrow', ENEMY_ARROW);
  f[F.Knife] = ol('Knife', KNIFE);
  f[F.Firebolt0] = ol('Firebolt0', FIREBOLT0, 'r');
  f[F.Firebolt1] = ol('Firebolt1', FIREBOLT1, 'r');
  f[F.Web] = ol('Web', WEB);
  f[F.Rock] = ol('Rock', ROCK);
  f[F.Axe] = ol('Axe', AXE);
  const bomb = spr('Bomb', BOMB);
  f[F.Bomb0] = outline(bomb);
  f[F.Bomb1] = over(outline(bomb), spr('BombSpark', BOMB_SPARK));
  f[F.Explosion0] = ol('Explosion0', EXPLOSION0, 'o');
  f[F.Explosion1] = spr('Explosion1', EXPLOSION1);
  f[F.Explosion2] = spr('Explosion2', EXPLOSION2);
  f[F.Spark] = spr('Spark', SPARK);
  f[F.Poof0] = ol('Poof0', POOF0, '3');
  f[F.Poof1] = ol('Poof1', POOF1, '3');
  f[F.Shield] = ol('Shield', SHIELD);
  f[F.Alert] = ol('Alert', ALERT);
  f[F.Heart] = ol('Heart', HEART);
  f[F.Coin0] = ol('Coin0', COIN0);
  f[F.Coin1] = ol('Coin1', COIN1);
  const key = spr('Key', KEY);
  f[F.KeyRed] = outline(key);
  f[F.KeyBlue] = outline(recolour(key, { R: 'U', o: 'c' }));
  f[F.Sparkle] = spr('Sparkle', SPARKLE);
  f[F.Frost] = ol('Frost', FROST, 'u');
  f[F.Slow] = spr('Slow', SLOW);
  f[F.ArrowPile] = ol('ArrowPile', ARROW_PILE);
  addMireFx(f);
  return f;
}
