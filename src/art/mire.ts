function flagstones(seed: number): Img {
  const img = blank(16, 16, 'F');
  const r = rng(seed);
  speckle(img, r, 'f', 8);
  speckle(img, r, 'I', 6);
  // four slabs to a tile, the joints staggered
  for (let x = 0; x < 16; x++) {
    set(img, x, 7, 'f');
    set(img, x, 15, 'f');
  }
  for (let y = 0; y < 7; y++) set(img, 9, y, 'f');
  for (let y = 8; y < 15; y++) set(img, 4, y, 'f');
  // a worn highlight along the top of each slab
  for (let x = 0; x < 16; x++) {
    if (x !== 9) set(img, x, 0, 'I');
    if (x !== 4) set(img, x, 8, 'I');
  }
  return img;
}

function flagstonesCracked(): Img {
  const img = flagstones(1909);
  const pts: Array<[number, number]> = [[11, 1], [12, 2], [12, 3], [13, 4], [14, 5], [12, 4], [11, 5], [1, 10], [2, 11], [2, 12], [3, 13]];
  for (const [x, y] of pts) set(img, x, y, 'C');
  return img;
}

function flagstonesMoss(): Img {
  const img = flagstones(2010);
  for (const [x, y] of [[2, 7], [3, 7], [4, 7], [9, 3], [9, 4], [10, 7], [4, 11], [4, 12], [5, 12], [13, 15], [14, 15]]) set(img, x, y, 'G');
  for (const [x, y] of [[3, 6], [9, 5], [5, 11], [14, 14]]) set(img, x, y, 'j');
  return img;
}

/** Top of a temple wall: dressed blocks in courses, far darker than the floor. */
function templeWallTop(): Img {
  const img = blank(16, 16, 'C');
  for (let x = 0; x < 16; x++) {
    set(img, x, 0, '0');
    set(img, x, 8, '0');
    set(img, x, 1, 'f');
    set(img, x, 9, 'f');
  }
  for (let y = 0; y < 8; y++) set(img, 5, y, '0');
  for (let y = 8; y < 16; y++) set(img, 12, y, '0');
  set(img, 6, 1, 'C');
  set(img, 13, 9, 'C');
  const r = rng(2111);
  for (let i = 0; i < 8; i++) {
    const x = Math.floor(r() * 16);
    const y = Math.floor(r() * 16);
    if (get(img, x, y) === 'C') set(img, x, y, '1');
  }
  return img;
}

