function bogBase(seed: number): Img {
  const img = blank(16, 16, 'W');
  const r = rng(seed);
  speckle(img, r, 'X', 16);
  for (let i = 0; i < 4; i++) {
    const x = Math.floor(r() * 16);
    const y = Math.floor(r() * 16);
    setWrap(img, x, y, 'Z');
    setWrap(img, x + 1, y, 'Z');
    if (i % 2) setWrap(img, x + 2, y, 'Z');
  }
  for (let i = 0; i < 3; i++) {
    const x = Math.floor(r() * 16);
    const y = Math.floor(r() * 16);
    setWrap(img, x, y, 'X');
    setWrap(img, x + 1, y, 'X');
    setWrap(img, x + 2, y, 'X');
  }
  return img;
}

function bogLilies(): Img {
  const img = bogBase(1606);
  const pad = (cx: number, cy: number, flower: boolean) => {
    for (let y = -1; y <= 1; y++) for (let x = -1; x <= 2; x++) if (!(x === 2 && y !== 0) || y === 0) setWrap(img, cx + x, cy + y, 'j');
    setWrap(img, cx, cy - 1, 'H');
    setWrap(img, cx - 1, cy, 'H');
    setWrap(img, cx + 1, cy, 'W'); // the notch
    setWrap(img, cx + 1, cy + 1, 'G');
    if (flower) {
      setWrap(img, cx, cy, 'q');
      setWrap(img, cx, cy + 1, 'k');
    }
  };
  pad(4, 4, true);
  pad(11, 9, false);
  pad(5, 12, false);
  return img;
}

function murk(): Img {
  const img = blank(16, 16, 'Q');
  const r = rng(1707);
  for (let i = 0; i < 6; i++) {
    const x = Math.floor(r() * 16);
    const y = Math.floor(r() * 16);
    setWrap(img, x, y, 'i');
    setWrap(img, x + 1, y, 'i');
    setWrap(img, x + 2, y, 'i');
    if (i % 3 === 0) setWrap(img, x + 1, y - 1, 'X');
  }
  return img;
}

