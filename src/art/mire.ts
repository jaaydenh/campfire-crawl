export function addMireTiles(t: Img[], cracks: Img, rubble: Img): void {
  const onMud = (sprite: Img, seed: number): Img => over(mudBase(seed), sprite);
  t[T.Mud] = mudBase(1101);
  t[T.Mud2] = mudPuddles();
  t[T.Mud3] = mudReeds();
  t[T.MireTree] = mireTree();
  t[T.MireTree2] = deadTree();
  t[T.Reeds] = onMud(ol('Reeds', REEDS, 'g'), 1505);
  t[T.Bog] = bogBase(1601);
  t[T.Bog2] = bogLilies();
  t[T.Murk] = murk();
  t[T.Sinking] = over(murk(), outline(spr('RaftPlanks', RAFT_PLANKS), '0'));
  t[T.TempleFloor] = flagstones(1808);
  t[T.TempleFloor2] = flagstonesCracked();
  t[T.TempleFloor3] = flagstonesMoss();
  t[T.TempleWall] = templeWallTop();
  t[T.TempleWallFace] = templeFaceTile();
  t[T.TempleCracked] = over(templeFaceTile(), cracks);
  t[T.TempleRubble] = over(flagstones(1818), rubble);
  t[T.Flood] = floodWater();
  t[T.Drained] = drained();
  t[T.Raft] = over(floodWater(), outline(spr('RaftStone', RAFT_STONE), '0'));
  t[T.Crumble] = over(flagstones(1828), spr('CrumbleGaps', CRUMBLE_GAPS));
}

export const templeFaceTile = (): Img => spr('TempleFace', TEMPLE_FACE);

