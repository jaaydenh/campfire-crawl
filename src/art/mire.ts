/** Second walk frame for an upright figure: the body drops 1px and the feet spread. `feet` is the colour of its feet. */
function stride(name: string, src: string, feet: string): Img {
  const rows = src
    .split('\n')
    .map((r) => r.trim())
    .filter((r) => r.length > 0);
  const out = ['................', ...rows.slice(0, 13), `....${feet}${feet}....${feet}${feet}....`, '................'];
  return spr(name, out.join('\n'));
}

