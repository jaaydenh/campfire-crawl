function floodWater(): Img {
  const img = blank(16, 16, 'J');
  const r = rng(2212);
  for (let i = 0; i < 7; i++) {
    const x = Math.floor(r() * 16);
    const y = Math.floor(r() * 16);
    setWrap(img, x, y, 'l');
    setWrap(img, x + 1, y, 'l');
    setWrap(img, x + 2, y, 'l');
    if (i % 3 === 0) setWrap(img, x + 3, y, 'c');
    if (i % 2 === 0) setWrap(img, x + 1, y + 2, 'n');
  }
  return img;
}

function drained(): Img {
  const img = recolour(flagstones(2313), { F: 'f', I: 'F', f: 'C' });
  for (const [x, y] of [[2, 3], [3, 3], [4, 3], [3, 4], [11, 11], [12, 11], [12, 12], [13, 12]]) set(img, x, y, 'J');
  for (const [x, y] of [[3, 2], [12, 10]]) set(img, x, y, 'l');
  for (const [x, y] of [[7, 5], [7, 6], [8, 13], [14, 3]]) set(img, x, y, 'G');
  set(img, 8, 12, 'j');
  return img;
}

