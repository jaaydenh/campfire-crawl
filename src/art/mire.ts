function speckle(img: Img, rand: () => number, key: string, n: number): void {
  for (let i = 0; i < n; i++) set(img, Math.floor(rand() * img.w), Math.floor(rand() * img.h), key);
}

// ================================================================ tiles

function mudBase(seed: number): Img {
  const img = blank(16, 16, 'M');
  const r = rng(seed);
  speckle(img, r, 'N', 22);
  speckle(img, r, 'L', 9);
  for (let i = 0; i < 3; i++) {
    const x = Math.floor(r() * 16);
    const y = Math.floor(r() * 16);
    setWrap(img, x, y, 'N');
    setWrap(img, x + 1, y, 'N');
    setWrap(img, x + 2, y + 1, 'N');
  }
  return img;
}

function mudPuddles(): Img {
  const img = mudBase(1202);
  const puddle = (cx: number, cy: number, rx: number, ry: number) => {
    for (let y = -ry; y <= ry; y++)
      for (let x = -rx; x <= rx; x++) {
        const d = (x * x) / (rx * rx + 0.5) + (y * y) / (ry * ry + 0.5);
        if (d <= 1) setWrap(img, cx + x, cy + y, d < 0.4 ? 'W' : 'X');
      }
    setWrap(img, cx - 1, cy - 1, 'Z');
  };
  puddle(4, 4, 2, 1);
  puddle(11, 10, 3, 1);
  puddle(5, 12, 1, 1);
  return img;
}

function mudReeds(): Img {
  const img = mudBase(1303);
  const tuft = (x: number, y: number) => {
    setWrap(img, x, y, 'j');
    setWrap(img, x, y + 1, 'G');
    setWrap(img, x + 1, y - 1, 'H');
    setWrap(img, x + 1, y, 'j');
    setWrap(img, x + 1, y + 1, 'G');
    setWrap(img, x + 2, y, 'G');
    setWrap(img, x + 2, y + 1, 'g');
  };
  tuft(2, 4);
  tuft(10, 3);
  tuft(6, 11);
  // a toadstool
  setWrap(img, 12, 11, 'R');
  setWrap(img, 13, 11, 'R');
  setWrap(img, 12, 12, '5');
  setWrap(img, 13, 12, 'N');
  return img;
}

/** Drooping swamp canopy: overlapping clumps like the forest tree, in darker, sicklier greens, hung with moss. */
function mireTree(): Img {
  const img = blank(16, 16, 'Q');
  const clumps: Array<[number, number, number]> = [
    [11.5, 11.5, 3.3], [7.5, 12.5, 2.9], [12.5, 7.5, 2.9], [3.8, 11.2, 3.1], [11.2, 3.8, 3.1], [8.2, 8.2, 3.5], [3.2, 7.2, 2.9], [7.2, 3.2, 3.0], [3.9, 3.9, 2.9],
  ];
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) if (Math.hypot(x - 7.5, y - 7.5) < 8.6) set(img, x, y, 'g');
  for (const [cx, cy, rad] of clumps) {
    for (let y = 0; y < 16; y++) {
      for (let x = 0; x < 16; x++) {
        const dx = x - cx;
        const dy = y - cy;
        const d = Math.hypot(dx, dy);
        if (d > rad) continue;
        const n = (-dx - dy) / (rad * 1.414);
        let c = 'g';
        if (n > 0.66) c = 'j';
        else if (n > 0.15) c = 'G';
        else if (n < -0.5 && d > rad - 1.1) c = 'Q';
        set(img, x, y, c);
      }
    }
  }
  // strands of moss
  for (const [x, y] of [[4, 5], [9, 4], [12, 9], [6, 10], [10, 13]]) {
    set(img, x, y, 'Z');
    set(img, x, y + 1, 'X');
  }
  return img;
}

/** A dead tree from above: bare limbs reaching out of the dark, moss on a few of them. */
function deadTree(): Img {
  const img = blank(16, 16, 'Q');
  const r = rng(1404);
  speckle(img, r, 'g', 40);
  speckle(img, r, 'X', 10);
  const limbs: Array<[number, number]> = [[1, 2], [13, 1], [15, 8], [12, 14], [3, 14], [0, 9], [8, 0], [7, 15]];
  for (const [x, y] of limbs) line(img, 8, 8, x, y, 'b');
  for (const [x, y] of limbs.slice(0, 5)) line(img, 8, 7, Math.round((8 + x) / 2), Math.round((7 + y) / 2), 'B');
  for (const [x, y] of [[7, 7], [8, 7], [7, 8], [8, 8]]) set(img, x, y, 'e');
  set(img, 7, 7, 'D');
  for (const [x, y] of [[3, 4], [12, 3], [11, 12], [4, 12]]) {
    set(img, x, y, 'Z');
    set(img, x, y + 1, 'X');
  }
  return img;
}

