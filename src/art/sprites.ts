// ---------------------------------------------------------------- digits (5x7 cell, 3x5 glyph)

const GLYPHS = [
  '111101101101111',
  '010110010010111',
  '111001111100111',
  '111001111001111',
  '101101111001001',
  '111100111001111',
  '111100111101111',
  '111001010010010',
  '111101111101111',
  '111101111001111',
];

export function buildDigits(): Img[] {
  return GLYPHS.map((g) => {
    const img = blank(5, 7);
    for (let i = 0; i < 15; i++) {
      if (g[i] === '1') set(img, 1 + (i % 3), 1 + Math.floor(i / 3), 'w');
    }
    return outline(img, '0', true);
  });
}
