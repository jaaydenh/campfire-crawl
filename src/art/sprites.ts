function chiefWalk(step: 0 | 1): Img {
  const img = blank(32, 32);
  const dy = step;
  stampRuns('ChiefCore', img, CHIEF_CORE, dy);
  stampRuns('ChiefBackArm', img, CHIEF_BACK_ARM_DOWN, dy);
  stampRuns('ChiefAxe', img, CHIEF_AXE, dy);
  stampRuns('ChiefFrontArm', img, CHIEF_FRONT_ARM_DOWN, dy);
  stampRuns('ChiefLegs', img, step === 0 ? CHIEF_LEGS_A : CHIEF_LEGS_B);
  return outline(img);
}

function chiefWindup(): Img {
  const img = blank(32, 32);
  stampRuns('ChiefCore', img, CHIEF_CORE, 1);
  stampRuns('ChiefBackArmUp', img, CHIEF_BACK_ARM_UP);
  // axe hoisted: only the upper part of it, lifted 2px, gripped just under the blade
  stampRuns('ChiefAxeUp', img, CHIEF_AXE.slice(0, 21), -2);
  stampRuns('ChiefFrontArmUp', img, CHIEF_FRONT_ARM_UP);
  stampRuns('ChiefLegs', img, CHIEF_LEGS_WIDE);
  return outline(img);
}

const ENRAGED = { s: 'o', S: 'R', w: 'Y' };

export function buildChief(): Img[] {
  const base = [chiefWalk(0), chiefWalk(1), chiefWindup()];
  return [...base, ...base.map((f) => recolour(f, ENRAGED))];
}

