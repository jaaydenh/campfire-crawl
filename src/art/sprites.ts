type Leg = [number, number, number, number, number, number];
const LEGS_P: Leg[] = [
  [11, 6, 13, 4, 14, 2],
  [10, 6, 11, 3, 11, 1],
  [9, 6, 8, 3, 7, 1],
  [8, 6, 6, 4, 4, 2],
];
const LEGS_Q: Leg[] = [
  [11, 6, 13, 4, 14, 4],
  [10, 6, 11, 3, 12, 2],
  [9, 6, 8, 3, 8, 1],
  [8, 6, 6, 3, 4, 1],
];

function spider(top: Leg[], bottom: Leg[]): Img {
  const legs = blank();
  for (const [x0, y0, x1, y1, x2, y2] of top) {
    line(legs, x0, y0, x1, y1, 'd');
    line(legs, x1, y1, x2, y2, 'd');
    set(legs, x1, y1, 'D');
  }
  for (const [x0, y0, x1, y1, x2, y2] of bottom) {
    line(legs, x0, 15 - y0, x1, 15 - y1, 'd');
    line(legs, x1, 15 - y1, x2, 15 - y2, 'd');
    set(legs, x1, 15 - y1, 'D');
  }
  return over(legs, ol('SpiderBody', SPIDER_BODY));
}

