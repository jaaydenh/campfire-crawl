/** Second walk frame for an upright humanoid: body drops 1px, legs spread into a stride. */
function stride(name: string, src: string): Img {
  const rows = src
    .split('\n')
    .map((r) => r.trim())
    .filter((r) => r.length > 0);
  const out = ['................', ...rows.slice(0, 13), '....bb....bb....', '................'];
  return spr(name, out.join('\n'));
}

