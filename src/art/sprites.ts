const TUNICS: Array<Record<string, string>> = [
  { T: 'u', t: 'n', E: 'U' }, // blue
  { T: 'R', t: 'r', E: 'o' }, // red
  { T: 'H', t: 'G', E: 'y' }, // green
  { T: 'O', t: 'a', E: 'Y' }, // gold
];

/** Swap the tunic placeholder keys in the source text before it is parsed. */
function tint(src: string, map: Record<string, string>): string {
  return src.replace(/[TtE]/g, (c) => map[c] ?? c);
}

export function buildHero(index: number): Img[] {
  const map = TUNICS[index];
  const frames: Array<[string, string]> = [
    ['HeroDown0', HERO_DOWN0],
    ['HeroDown1', HERO_DOWN1],
    ['HeroUp0', HERO_UP0],
    ['HeroUp1', HERO_UP1],
    ['HeroSide0', HERO_SIDE0],
    ['HeroSide1', HERO_SIDE1],
  ];
  return frames.map(([name, src]) => spr(name, tint(src, map)));
}

