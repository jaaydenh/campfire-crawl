export function buildObjects(): Img[] {
  const o: Img[] = [];
  const campfire = spr('Campfire', CAMPFIRE);
  const flameA = spr('FlameA', FLAME_A);
  const flameB = spr('FlameB', FLAME_B);
  o[O.CampfireOff] = outline(campfire);
  o[O.CampfireOn0] = outline(over(campfire, flameA, 0, 1));
  o[O.CampfireOn1] = outline(over(campfire, flameB, 0, 1));
  o[O.ChestClosed] = ol('ChestClosed', CHEST_CLOSED);
  o[O.ChestOpen] = ol('ChestOpen', CHEST_OPEN);
  o[O.Pot] = ol('Pot', POT);
  o[O.PotBroken] = ol('PotBroken', POT_BROKEN);
  o[O.Sign] = ol('Sign', SIGN);
  const door = spr('Door', DOOR);
  o[O.DoorRed] = door;
  o[O.DoorBlue] = recolour(door, { R: 'u', r: 'n', o: 'U' });
  o[O.Gate] = spr('Gate', GATE);
  o[O.PlateUp] = ol('PlateUp', PLATE_UP);
  o[O.PlateDown] = ol('PlateDown', PLATE_DOWN);
  o[O.Block] = ol('Block', BLOCK);
  const lever = spr('Lever', LEVER);
  o[O.LeverOff] = outline(lever);
  o[O.LeverOn] = outline(recolour(mirror(lever), { R: 'H', r: 'G', o: 'y' }));
  const brazier = spr('Brazier', BRAZIER);
  const litBrazier = over(brazier, spr('BrazierCoals', BRAZIER_LIT_COALS));
  o[O.BrazierOff] = outline(brazier);
  o[O.BrazierOn0] = outline(over(litBrazier, flameA, 0, -2));
  o[O.BrazierOn1] = outline(over(litBrazier, flameB, 0, -2));
  o[O.SpikesDown] = spr('SpikesDown', SPIKES_DOWN);
  o[O.SpikesUp] = ol('SpikesUp', SPIKES_UP);
  o[O.ArrowTrap] = ol('ArrowTrap', ARROW_TRAP);
  const shrine = spr('Shrine', SHRINE);
  o[O.Shrine] = over(outline(shrine), spr('ShrineGlow', SHRINE_GLOW));
  o[O.ShrineUsed] = outline(recolour(shrine, { Y: '4', O: '3', a: '2' }));
  o[O.Pedestal] = ol('Pedestal', PEDESTAL);
  o[O.Den] = ol('Den', DEN);
  o[O.Nest] = nest();
  o[O.Sconce] = over(wallFaceTile(), ol('Sconce', SCONCE));
  o[O.SconceOdd] = over(wallFaceTile(), ol('SconceOdd', SCONCE_ODD));
  o[O.Tent] = ol('Tent', TENT);
  o[O.Crate] = ol('Crate', CRATE);
  o[O.Barrel] = ol('Barrel', BARREL);
  o[O.Mushroom] = ol('Mushroom', MUSHROOM);
  o[O.Bones] = ol('Bones', BONES);
  o[O.Stump] = shift(ol('Stump', STUMP), 0, 1);
  return o;
}
