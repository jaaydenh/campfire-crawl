function nest(): Img {
  const egg = spr('Egg', EGG, 6, 6);
  const web = blank();
  // strands anchoring the cluster
  line(web, 1, 1, 6, 5, '4');
  line(web, 14, 1, 10, 5, '4');
  line(web, 1, 14, 5, 11, '4');
  line(web, 14, 14, 11, 10, '4');
  line(web, 0, 8, 3, 8, '4');
  line(web, 15, 7, 13, 8, '4');
  line(web, 8, 0, 8, 3, '4');
  line(web, 7, 15, 7, 13, '4');
  // eggs stamped back-to-front so each keeps its own dark rim
  const at: Array<[number, number]> = [
    [5, 2], [2, 5], [8, 5], [5, 8], [9, 9],
  ];
  let out = web;
  for (const [x, y] of at) out = over(out, egg, x, y);
  return out;
}

